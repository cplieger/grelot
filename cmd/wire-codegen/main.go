// Command wire-codegen writes the web UI's typed client,
// internal/webui/static-src/src/wire/*.gen.ts, and docs/openapi.json from
// the web API's route table and types in internal/webui/wire.
//
// Run: go run ./cmd/wire-codegen (from the repo root)
package main

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"

	"github.com/cplieger/go/wiregen/v2"
	"github.com/cplieger/grelot/internal/webui/wire"
)

const headerComment = "// Code generated by cmd/wire-codegen. DO NOT EDIT.\n\n"

func main() { os.Exit(run()) }

func run() int {
	// Loading packages runs go as a subprocess; an interrupt cancels it.
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := generate(ctx, "."); err != nil {
		if errors.Is(err, context.Canceled) {
			fmt.Fprintln(os.Stderr, "wire-codegen: interrupted")
			return 130
		}
		fmt.Fprintf(os.Stderr, "wire-codegen: %v\n", err)
		return 1
	}
	fmt.Println("wire-codegen: generated internal/webui/static-src/src/wire/*.gen.ts and docs/openapi.json")
	return 0
}

// generate writes every generated file under root, at the paths the
// committed tree holds them.
func generate(ctx context.Context, root string) error {
	return registry().Generate(ctx,
		wiregen.WithTSDir(filepath.Join(root, "internal", "webui", "static-src", "src", "wire")),
		wiregen.WithTransportImport("../transport.js"),
		wiregen.WithHeaderComment(headerComment),
		wiregen.WithRequireJSONTags(true),
		wiregen.WithOpenAPIFiles(filepath.Join(root, "docs", "openapi.json")),
	)
}

func registry() *wiregen.Registry {
	return &wiregen.Registry{
		ErrorEnvelope: wiregen.TypeRef[wire.Error](),
		OpenAPI: wiregen.OpenAPIInfo{
			Title:       "grelot web API",
			Version:     "2",
			Description: "The routes the web UI calls, under /api, for a signed-in session.",
		},
		Enums: []wiregen.EnumRef{
			wiregen.StringEnum[wire.Show](),
			wiregen.StringEnum[wire.ThreadKind](),
			wiregen.StringEnum[wire.SenderKind](),
			wiregen.StringEnum[wire.ReservationState](),
			wiregen.StringEnum[wire.AgentState](),
			wiregen.StringEnum[wire.StatsRange](),
			wiregen.StringEnum[wire.EventKind](),
		},
		// The types a route's own types reach; a route's own are registered
		// by naming them on its endpoint.
		Types: []wiregen.Type{
			wiregen.TypeRef[wire.Thread](), wiregen.TypeRef[wire.LastPost](), wiregen.TypeRef[wire.ConversationRow](),
			wiregen.TypeRef[wire.ConversationCounts](),
			wiregen.TypeRef[wire.ReadCount](), wiregen.TypeRef[wire.Post](), wiregen.TypeRef[wire.Reservation](),
			wiregen.TypeRef[wire.Agent](), wiregen.TypeRef[wire.Receipt](), wiregen.TypeRef[wire.PostTarget](),
			wiregen.TypeRef[wire.HistoryPost](), wiregen.TypeRef[wire.PostBucket](), wiregen.TypeRef[wire.AgentStats](),
			wiregen.TypeRef[wire.ThreadStats](), wiregen.TypeRef[wire.DelayHistogram](), wiregen.TypeRef[wire.Sample](),
			wiregen.TypeRef[wire.Event](), wiregen.TypeRef[wire.EventCounts](), wiregen.TypeRef[wire.HeldTurns](),
			wiregen.TypeRef[wire.Methods](),
		},
		Endpoints: endpoints(wire.Routes),
		Events:    []wiregen.Event{{Name: wire.EventChanged, Data: wiregen.TypeRef[wire.Changed]()}},
	}
}

// idempotencyKey is a keyed route's header, whose byte bounds count the
// key's two quotes.
var idempotencyKey = wiregen.Header{
	Name: "Idempotency-Key", Arg: "idempotencyKey", Required: true,
	MinBytes: wire.IdempotencyKeyMin + 2, MaxBytes: wire.IdempotencyKeyMax + 2,
	Description: fmt.Sprintf("A new quoted random key of %d to %d letters, digits, - or _ per post, the same key when it is sent again.",
		wire.IdempotencyKeyMin, wire.IdempotencyKeyMax),
}

func endpoints(routes []wire.Route) []wiregen.Endpoint {
	out := make([]wiregen.Endpoint, 0, len(routes))
	for i := range routes {
		r := &routes[i]
		e := wiregen.Endpoint{
			Name: r.Name, Method: r.Method, Path: r.Path, Summary: r.Summary, Status: r.Status,
			Params: wiregen.TypeOf(r.Params), Query: wiregen.TypeOf(r.Query),
			Request: wiregen.TypeOf(r.Request), Response: wiregen.TypeOf(r.Response),
			Kind: wiregen.KindJSON,
		}
		if r.Kind == wire.KindEventStream {
			e.Kind = wiregen.KindEventStream
		}
		if r.Keyed {
			e.Headers = []wiregen.Header{idempotencyKey}
		}
		for _, c := range r.Errors {
			e.Errors = append(e.Errors, wiregen.ErrorRef{Code: c.Code, Status: c.Status})
		}
		out = append(out, e)
	}
	return out
}
